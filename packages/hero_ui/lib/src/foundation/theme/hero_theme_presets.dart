/// The named theme presets of the HeroUI theme builder
/// (https://heroui.com/en/themes).
///
/// Every preset ships a light and a dark variant. Values are taken verbatim
/// from HeroUI's generated `theme-presets.css`; hover, soft and border shades
/// are derived by [HeroColors.derive].
enum HeroThemePreset {
  /// The HeroUI default theme (spelled `standard` because `default` is a
  /// reserved word in Dart).
  standard('Default'),

  /// Soft light-blue accent.
  sky('Sky'),

  /// Soft violet accent.
  lavender('Lavender'),

  /// Soft green accent.
  mint('Mint'),

  /// Red accent on warm neutrals with extra-small radii.
  netflix('Netflix'),

  /// Monochrome black accent with small radii.
  uber('Uber'),

  /// Green accent with extra-small field radii.
  spotify('Spotify'),

  /// Blue accent with extra-small field radii.
  coinbase('Coinbase'),

  /// Coral accent with white accent foreground.
  airbnb('Airbnb'),

  /// Blurple accent on tinted neutrals with small radii.
  discord('Discord'),

  /// Orange accent with extra-large field radii.
  rabbit('Rabbit');

  const HeroThemePreset(this.label);

  /// Display name used by the HeroUI theme builder.
  final String label;

  /// The light color source for this preset.
  HeroColorSource get lightSource => switch (this) {
    HeroThemePreset.standard => HeroColorSource.light,
    HeroThemePreset.sky => _skyLight(),
    HeroThemePreset.lavender => _lavenderLight(),
    HeroThemePreset.mint => _mintLight(),
    HeroThemePreset.netflix => _netflixLight(),
    HeroThemePreset.uber => _uberLight(),
    HeroThemePreset.spotify => _spotifyLight(),
    HeroThemePreset.coinbase => _coinbaseLight(),
    HeroThemePreset.airbnb => _airbnbLight(),
    HeroThemePreset.discord => _discordLight(),
    HeroThemePreset.rabbit => _rabbitLight(),
  };

  /// The dark color source for this preset.
  HeroColorSource get darkSource => switch (this) {
    HeroThemePreset.standard => HeroColorSource.dark,
    HeroThemePreset.sky => _skyDark(),
    HeroThemePreset.lavender => _lavenderDark(),
    HeroThemePreset.mint => _mintDark(),
    HeroThemePreset.netflix => _netflixDark(),
    HeroThemePreset.uber => _uberDark(),
    HeroThemePreset.spotify => _spotifyDark(),
    HeroThemePreset.coinbase => _coinbaseDark(),
    HeroThemePreset.airbnb => _airbnbDark(),
    HeroThemePreset.discord => _discordDark(),
    HeroThemePreset.rabbit => _rabbitDark(),
  };

  /// The `--radius` override of this preset in logical pixels, or null when
  /// the preset keeps the default (8).
  double? get radius => _presetRadii[this]?.$1;

  /// The `--field-radius` override of this preset in logical pixels, or null
  /// when the preset keeps the default (12).
  double? get fieldRadius => _presetRadii[this]?.$2;
}

